section .text
armor_and_tools:
    sub rsp, 40

armor_and_tools_start:
    call draw_menu

select_menu:
    call _getch
    cmp al, 224
    jne checkEnter
    call _getch

    cmp al, 72
    je up

    cmp al, 80
    je down

up:
    dec byte [selected]
    call check_selected
    call draw_menu
    jmp select_menu

down:
    inc byte [selected]
    call check_selected
    call draw_menu
    jmp select_menu

checkEnter:
    cmp al, 13
    jne select_menu

    movzx eax, byte [selected]

    cmp eax, 1
    je copper
    cmp eax, 2
    je lapis
    cmp eax, 3
    je pink_gold
    cmp eax, 4
    je amethyst
    cmp eax, 5
    je redstone
    cmp eax, 6
    je quartz
    cmp eax, 7
    je emerald
    cmp eax, 8
    je red_diamond
    cmp eax, 9
    je sky_crystal
    cmp eax, 10
    je hell_crystal
    cmp eax, 11
    je wolfram
    cmp eax, 12
    je red_nethrite
    cmp eax, 13
    je enderite
    cmp eax, 14
    je exit

    jmp select_menu

; DRAW
draw_menu:
    sub rsp, 40
    call console_clear

    call color_def
    lea rcx, [message]
    call printf

    xor r12, r12

draw_loop:
    cmp r12, itemCount
    je draw_done

    movzx eax, byte [selected]
    dec eax

    cmp r12d, eax
    je draw_selected

draw_normal:
    call color_red
    jmp draw_print

draw_selected:
    call color_green

draw_print:
    lea rbx, [menu]
    mov rcx, [rbx + r12*8]
    call printf

    inc r12
    jmp draw_loop

draw_done:
    add rsp, 40
    ret

